-- One row per question a run asked about a trial, with the model's answer in the same row (ADR-004):
-- what was asked (the registered item, the pages shown, whether it was asked again with every page) and
-- what the model answered (found or not, its quote and page, whether the quote is really on that page).
-- `evidence_id` numbers the answers the model gave (NULL: it gave none for this question); the rules
-- trace of a judgement names them.
SET LOCAL trialwatch.actor = '1';

CREATE TABLE checks.answer (
    run_id              bigint NOT NULL REFERENCES checks.run,
    trial_id            bigint NOT NULL REFERENCES core.trial,
    -- the requirement's key, e.g. participants, endpoint:<registered endpoint id>
    key                 text NOT NULL,
    -- the registered item the question is about (e.g. the endpoint's text), if any
    item_text           text,
    -- pages shown in the call that answered it: [{"file": <sha256 hex>, "page": n}, ...]
    pages               jsonb NOT NULL,
    -- true when it was asked again with every page
    widened             boolean NOT NULL DEFAULT false,
    -- the model's answer, all NULL when it gave none
    evidence_id         bigint UNIQUE,
    -- true: found; false: not found; NULL: the model said it doesn't know
    found               boolean,
    -- numeric_result | narrative_only | chart_only | redacted | not_analysed | other
    kind                text,
    quote               text,
    -- the document version and page the quote cites
    document_version_id bigint REFERENCES core.document_version,
    file_sha256         bytea REFERENCES core.file,
    page_no             integer,
    note                text,
    -- the quote occurs (normalised) on the cited page; unverified evidence is ignored by the rules
    verified            boolean,
    PRIMARY KEY (run_id, trial_id, key),
    CHECK ((evidence_id IS NULL) = (verified IS NULL))
);
COMMENT ON TABLE checks.answer IS 'each question a run asked about a trial, with the answer the model gave (if any)';
CREATE SEQUENCE checks.answer_evidence_id_seq OWNED BY checks.answer.evidence_id;
CREATE INDEX answer_file_idx ON checks.answer (file_sha256) WHERE file_sha256 IS NOT NULL;

-- the questions and their evidence, as one row each; the evidence keeps its id (traces name it)
INSERT INTO checks.answer (run_id, trial_id, key, item_text, pages, widened, evidence_id, found, kind, quote,
                           document_version_id, file_sha256, page_no, note, verified)
SELECT q.run_id, q.trial_id, q.key, q.item_text, q.pages, q.widened, e.id, e.found, e.kind, e.quote,
       e.document_version_id, e.file_sha256, e.page_no, e.note, e.verified
FROM checks.question q
LEFT JOIN checks.evidence e ON e.run_id = q.run_id AND e.trial_id = q.trial_id AND e.key = q.key;
SELECT setval('checks.answer_evidence_id_seq', coalesce((SELECT max(id) FROM checks.evidence), 0) + 1, false);

DROP TABLE checks.evidence;
DROP TABLE checks.question;


