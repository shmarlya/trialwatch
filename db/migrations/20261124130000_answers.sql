SET LOCAL trialwatch.actor = '1';

CREATE TABLE checks.question (
    run_id    bigint NOT NULL REFERENCES checks.run,
    trial_id  bigint NOT NULL REFERENCES core.trial,
    key       text NOT NULL,
    item_text text,
    pages     jsonb NOT NULL,
    widened   boolean NOT NULL DEFAULT false,
    PRIMARY KEY (run_id, trial_id, key)
);
CREATE TABLE checks.evidence (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id              bigint NOT NULL,
    trial_id            bigint NOT NULL,
    key                 text NOT NULL,
    found               boolean,
    kind                text,
    quote               text,
    document_version_id bigint REFERENCES core.document_version,
    file_sha256         bytea REFERENCES core.file,
    page_no             integer,
    note                text,
    verified            boolean NOT NULL,
    FOREIGN KEY (run_id, trial_id, key) REFERENCES checks.question
);
CREATE INDEX evidence_question_idx ON checks.evidence (run_id, trial_id, key);
INSERT INTO checks.question SELECT run_id, trial_id, key, item_text, pages, widened FROM checks.answer;
INSERT INTO checks.evidence (id, run_id, trial_id, key, found, kind, quote, document_version_id, file_sha256,
                             page_no, note, verified)
SELECT evidence_id, run_id, trial_id, key, found, kind, quote, document_version_id, file_sha256, page_no, note, verified
FROM checks.answer WHERE evidence_id IS NOT NULL;
SELECT setval(pg_get_serial_sequence('checks.evidence', 'id'), coalesce((SELECT max(id) FROM checks.evidence), 0) + 1, false);
DROP TABLE checks.answer;
